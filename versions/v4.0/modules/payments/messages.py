# ==================== SUBSCRIPTION STATUS ====================

def get_subscription_status_text(subscription: Optional[Subscription]) -> str:
    """
    Get formatted subscription status text.

    Args:
        subscription: Subscription object or None

    Returns:
        Formatted status string
    """
    if subscription and subscription.is_active:
        # Check if subscription is time-based and not expired
        if subscription.end_date and subscription.end_date > datetime.utcnow():
            end_date_str = subscription.end_date.strftime('%d.%m.%Y')
            return f"🔐 У вас активная подписка до {end_date_str}."
        # Subscription marked active, но срок уже прошёл
        return "🔐 У вас нет активной подписки."

    return "🔐 У вас нет активной подписки."


