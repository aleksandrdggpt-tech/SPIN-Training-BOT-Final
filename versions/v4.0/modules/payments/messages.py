def format_days_left(days: int) -> str:
    """Format days remaining in subscription."""
    if days == 0:
        return "сегодня"
    elif days == 1:
        return "завтра"
    elif days <= 4:
        return f"{days} дня"
    else:
        return f"{days} дней"


